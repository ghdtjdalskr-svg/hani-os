// Reuse the canonical monthly engine without editing its generated main region.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url),source=fs.readFileSync(new URL('hani-main.js',root),'utf8');
const start=source.indexOf('const core=(()=>{'),end=source.indexOf('const store=(()=>{');
if(start<0||end<=start)throw Error('Canonical monthly core anchors missing; stop generation');
const output='// Generated by scripts/hani-goal-month-core.mjs from hani-main.js canonical core. Do not edit.\n'+source.slice(start,end).replace(/\r\n/g,'\n')+'\nexport default core;\n';
const read=file=>fs.readFileSync(new URL(file,root),'utf8').replace(/\r\n/g,'\n');
const period=read('data-hub/period-goal.mjs'),projection=read('data-hub/goal-period-view.mjs'),ui=read('hani-goal-progress.mjs');
const exported=[...period.matchAll(/^export (?:const|function) (\w+)/gm)].map(m=>m[1]);
const bundle='// Generated by scripts/hani-goal-month-core.mjs. Do not edit.\n(function(){\n"use strict";\n'+source.slice(start,end).replace(/\r\n/g,'\n')+
 'const periodEngine=(()=>{\n'+period.replace(/^export /gm,'')+'\nreturn {'+exported.join(',')+'};\n})();\n'+
 'const {EXTRA_DEFINITIONS,EXTRA_ADAPTERS,periodMonths,aggregatePeriod,resolvePeriodGoal,goalProgress,suggestMonthlyBudget}=periodEngine;\n'+
 projection.replace(/^import .*;\n/gm,'').replace(/^export /gm,'')+'\n'+ui.replace(/^import .*;\n/gm,'')+'\n})();\n';
for(const [file,text] of [['data-hub/month-core.generated.mjs',output],['hani-goal-progress.js',bundle]]){
 const target=new URL(file,root);
 if(process.argv.includes('--check')){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==text)throw Error(file+' is stale');}
 else {fs.writeFileSync(target,text);console.log('Generated '+fileURLToPath(target));}
}
if(process.argv.includes('--check'))console.log('PASS canonical monthly core and runtime bundle generation parity');
