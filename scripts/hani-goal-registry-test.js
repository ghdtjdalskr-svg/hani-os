'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict'),path=require('node:path');
const source=fs.readFileSync(path.join(__dirname,'../hani-main.js'),'utf8');
const context={structuredClone,Intl,Date};vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('const GOAL_METRICS='),source.indexOf('function renderGoalRegistry(')),context);
const make=context.goalRegistryBuildDraft,clock='2026-10-05T00:00:00.000Z';
const input={metric_id:'body_weight_kg',goal_type:'quarter',year:2026,quarter:4,value:95,effective_from:'2026-10-05'};
const original=[],draft=make(original,input,clock,'g');
assert.equal(original.length,0,'draft creates no mutation');
assert.equal(draft.entry.unit,'kg');assert.equal(draft.entry.revision,1);
const before=JSON.stringify(draft.next),updated=make(draft.next,{...input,value:94,effective_from:'2026-11-01'},clock,'unused');
assert.equal(JSON.stringify(draft.next),before,'revision draft preserves original');
assert.equal(updated.next[0].status,'superseded');assert.equal(updated.next[0].effective_to,'2026-10-31');
assert.equal(updated.entry.goal_id,'g');assert.equal(updated.entry.revision,2);
assert.throws(()=>make(draft.next,input,clock,'x'),/既存|기존/);
assert.throws(()=>make([],{...input,effective_from:'2026-10-04'},clock,'x'));
assert.throws(()=>make([],{...input,metric_id:'quiz_accuracy_percent',value:101},clock,'x'));
assert.throws(()=>make([],{...input,value:''},clock,'x'));
assert.throws(()=>make([],{...input,effective_from:'2027-01-01'},clock,'x'));
const annual=make([],{...input,goal_type:'annual'},clock,'a');assert.equal(annual.entry.effective_to,'2026-12-31');
console.log('PASS: no draft mutation, revisions preserve old values, effective dates, invalid targets and annual bounds');
