'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../hani-main.js'),'utf8');
const start=source.indexOf('function cloudHasMeaningfulLocalData(');
const end=source.indexOf('function cloudLocalStatusLabel(',start);
const base={accounts:[],goals:{},profile:{}};
const context={state:base,freshState:()=>structuredClone(base),cloudSame:(a,b)=>JSON.stringify(a)===JSON.stringify(b)};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
const meaningful=context.cloudHasMeaningfulLocalData;
assert.equal(meaningful(base),false);
assert.equal(meaningful({...base,goalRegistry:[]}),false);
const goalOnly={...base,goalRegistry:[{goal_id:'test-goal',revision:1}]};
const before=JSON.stringify(goalOnly);
assert.equal(meaningful(goalOnly),true,'goal-only Local must not be treated as empty');
assert.equal(JSON.stringify(goalOnly),before,'classification never mutates source');
assert.equal(meaningful({...base,books:[{id:'book'}]}),true);
assert.equal(meaningful({...base,goals:{readingAnnual:10}}),true);
assert.equal(meaningful({...base,pageNotes:{home:'note'}}),true);
assert.equal(meaningful({...base,goalRegistry:null}),false);
const fingerprintStart=source.indexOf('function cloudComparableState(');
const fingerprintEnd=source.indexOf('function cloudHasMeaningfulLocalData(',fingerprintStart);
context.structuredClone=structuredClone;
vm.runInContext(source.slice(fingerprintStart,fingerprintEnd),context);
assert.deepEqual(JSON.parse(JSON.stringify(context.cloudSyncFingerprintState(goalOnly))).goalRegistry,goalOnly.goalRegistry,'goal history participates in existing conflict fingerprint');
const normalizeStart=source.indexOf('function normalizeState(');
const normalizeEnd=source.indexOf('function save(',normalizeStart);
assert.match(source.slice(normalizeStart,normalizeEnd),/\.\.\.base,\.\.\.\(d\|\|\{\}\)/,'normalizer preserves additive data fields');
const decisionStart=source.indexOf('function cloudSyncDecision(');
const decisionEnd=source.indexOf('\nfunction ',decisionStart+1);
vm.runInContext(source.slice(decisionStart,decisionEnd),context);
const clocks={hasBaseline:true,baselineHash:'B',appliedRevision:5,remoteRevision:6};
assert.equal(context.cloudSyncDecision({...clocks,localMeaningful:meaningful(goalOnly),remoteMeaningful:true,localHash:'L',remoteHash:'R'}).action,'conflict','goal-only changes must not auto-pull over Local');
assert.equal(context.cloudSyncDecision({...clocks,localMeaningful:true,remoteMeaningful:true,localHash:'B',remoteHash:'R'}).action,'pull','unchanged Local keeps existing safe pull decision');
console.log('PASS: goal-only Local preservation, empty registry, existing data classification, zero mutation');
