import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {resolveRuntimeClosure} from '../../../scripts/hani-runtime-closure.mjs';
const root=path.resolve(import.meta.dirname,'../../..');
process.chdir(root);
const read=file=>fs.readFileSync(file);
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const baseline=JSON.parse(read('artifacts/pb-toon/stage2/baseline.json'));
const original=JSON.parse(read('artifacts/pb-toon/baseline.json'));
const changes=Object.entries(original).filter(([file,digest])=>hash(read(file))!==digest).map(([file])=>file).sort();
assert.deepEqual(changes,['hani-procrastination-board.css','hani-procrastination-board.js']);
assert.deepEqual(fs.readdirSync('.').filter(file=>/\.(js|css|html)$/.test(file)),baseline.rootRuntime);
const closure=await resolveRuntimeClosure({exists:fs.existsSync,read});
assert.deepEqual(closure.missing,[]);
const added=closure.files.filter(file=>!baseline.closure.files.includes(file));
assert.deepEqual(added,['assets/procrastination/pb-chibi-sheet-v1.webp']);
assert.equal(hash(read(added[0])),hash(read('artifacts/pb-toon/drafts/pb-chibi-sheet-v1.webp')));
const source=read('hani-procrastination-board.js').toString('utf8');
assert.doesNotMatch(source,/\?\?|\uFFFD/,'no broken replacement characters');
const before=read('artifacts/pb-toon/stage2/before-hani-procrastination-board.js').toString('utf8');
const staff=code=>code.slice(code.indexOf('  const STAFF = {'),code.indexOf('  const SPECS = ['));
assert.equal(staff(source),staff(before).replace(/, image:'[^']+'/g,''),'STAFF dialogue bytes preserved');
const result={status:'PASS',base:'a28918df50ba5fef3e7dab498eaa5eec4a27a103',runtimeChanged:[...changes,...added],sheetBytes:read(added[0]).length,sheetSha256:hash(read(added[0])),runtimeHashes:Object.fromEntries([...changes,...added].map(file=>[file,hash(read(file))])),preservedStage1Files:Object.keys(original).length-changes.length,indexUnchanged:true,mainUnchanged:true,version:'2.9.283 unchanged',closureBefore:baseline.closure.files.length,closureAfter:closure.files.length,closure160Limit:{status:closure.files.length<=160?'PASS':'FAIL',excess:Math.max(0,closure.files.length-160)},missing:closure.missing,rawRuntime:true,browser:'BLOCKED',screenshots:0};
fs.writeFileSync('artifacts/pb-toon/stage2/final-audit.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result,null,2));
